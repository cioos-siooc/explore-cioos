"""Limits OBIS occurrences to Canadian waters (EEZ + land); datasets from the
OBIS Canada or OTN-OBIS nodes are exempt. The polygon is regenerated by
``scripts/build_canada_eez_land_wkt.py``."""
import logging
from importlib.resources import files
from pathlib import Path

import numpy as np
from shapely import contains, points
from shapely import wkt as shp_wkt

logger = logging.getLogger(__name__)

DEFAULT_EXEMPT_NODE_IDS = frozenset({
    "7dfb2d90-9317-434d-8d4e-64adf324579a",   # OBIS Canada
    "68f83ea7-69a7-44fd-be77-3c3afd6f3cf8",   # OTN-OBIS
})


def _packaged_polygon_path() -> Path:
    return Path(str(files("cde_harvester.data") / "canada_eez_land.wkt"))


def load_boundary_polygon(polygon_file=None):
    """Public: discovery needs the polygon even under ``mode="none"``."""
    path = Path(polygon_file) if polygon_file else _packaged_polygon_path()
    return shp_wkt.loads(path.read_text().strip())


class ObisGeoFilter:
    def __init__(self, mode="canada", polygon_file=None, exempt_node_ids=None):
        if mode not in ("canada", "none"):
            raise ValueError(f"Unsupported geo filter mode: {mode!r}")
        self.mode = mode
        self.polygon_file = polygon_file
        self.exempt_node_ids = frozenset(exempt_node_ids) if exempt_node_ids else DEFAULT_EXEMPT_NODE_IDS
        self.polygon = None
        if mode == "canada":
            self.polygon = load_boundary_polygon(polygon_file)

    @classmethod
    def from_config(cls, cfg=None):
        cfg = cfg or {}
        unknown = set(cfg) - {"mode", "polygon_file", "exempt_node_ids"}
        if unknown:
            raise ValueError(
                f"Unknown obis_geo_filter key(s): {sorted(unknown)}. "
                "Valid keys: mode, polygon_file, exempt_node_ids"
            )
        return cls(
            mode=cfg.get("mode", "canada"),
            polygon_file=cfg.get("polygon_file"),
            exempt_node_ids=cfg.get("exempt_node_ids"),
        )

    def is_exempt(self, metadata: dict) -> bool:
        if self.mode == "none":
            return True
        return any(node.get("id") in self.exempt_node_ids for node in metadata.get("nodes") or [])

    def extent_intersects(self, extent_wkt):
        """None when the extent is missing or unparseable: fetch the full dataset."""
        if self.mode == "none" or not extent_wkt:
            return None
        try:
            return shp_wkt.loads(extent_wkt).intersects(self.polygon)
        except Exception as e:
            logger.warning("Could not parse dataset extent WKT: %s", e)
            return None

    def bounds(self):
        """(lon_min, lat_min, lon_max, lat_max): a superset pre-filter for
        filter_points; None under mode="none"."""
        if self.mode == "none" or self.polygon is None:
            return None
        return self.polygon.bounds

    def filter_points(self, lat, lon) -> np.ndarray:
        if self.mode == "none":
            return np.ones(len(lat), dtype=bool)
        return contains(self.polygon, points(lon, lat))
